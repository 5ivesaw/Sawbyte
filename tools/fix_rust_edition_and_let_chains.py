#!/usr/bin/env python3
"""
Sawbyte v0.5.1 Rust Edition, Let-Chain, Workspace, Build-Script & Lockfile Safeguard
(`tools/fix_rust_edition_and_let_chains.py`).

Runs automatically in GitHub Actions (`ci.yml`, `benchmarks.yml`, `player.yml`) and locally:
1. Invokes `tools/find_and_fix_bugs.py` to clean stale non-canonical files (`build.rs`, `src/bin`,
   leftover assimilated files), rewrite unsafe `env!("...")` macros to `option_env!`, inject any
   missing external crate dependencies into `Cargo.toml`, and verify `LiveSessionTransport` imports.
2. Rewrites any chained `if let ... && let ...` expressions into tuple destructuring.
3. Preserves any custom `[dependencies]` in `Cargo.toml` while ensuring `build = false` and `autobins = false`
   on `sawbyte-prepare`, `sawbyte-sim-core`, and `sawbyte-ctl`.
4. Synchronizes `Cargo.lock` and `native/Cargo.lock` to version `0.5.1`.
"""

from __future__ import annotations

from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]

WORKSPACE_MEMBERS = {
    "sawbyte-core",
    "sawbyte-protocol",
    "sawbyte-cli",
    "sawbyte-sim-core",
    "sawbyte-prepare",
    "sawbyte-ctl",
}


def ensure_editions_and_manifests_preserving_deps(root: Path) -> None:
    root_cargo = root / "Cargo.toml"
    if root_cargo.exists():
        txt = root_cargo.read_text(encoding="utf-8")
        updated = re.sub(
            r'(\[workspace\.package\][^\[]*?edition\s*=\s*)"2021"',
            r'\1"2024"',
            txt,
            flags=re.DOTALL,
        )
        updated = re.sub(
            r'(\[workspace\.package\][^\[]*?version\s*=\s*)"0\.5\.0"',
            r'\1"0.5.1"',
            updated,
            flags=re.DOTALL,
        )
        if updated != txt:
            root_cargo.write_text(updated, encoding="utf-8")
            print("[Safeguard] Updated root Cargo.toml [workspace.package] to v0.5.1 / edition 2024")

    for rfmt in [root / "rustfmt.toml", root / "native" / "rustfmt.toml"]:
        if not rfmt.exists() or 'edition = "2024"' not in rfmt.read_text(encoding="utf-8"):
            rfmt.parent.mkdir(parents=True, exist_ok=True)
            rfmt.write_text('edition = "2024"\n', encoding="utf-8")

    # Ensure build = false and autobins = false in sawbyte-prepare, sawbyte-sim-core, sawbyte-ctl
    # WITHOUT wiping out any [dependencies] in Cargo.toml!
    for crate_name in ("sawbyte-prepare", "sawbyte-sim-core", "sawbyte-ctl"):
        ctoml = root / "crates" / crate_name / "Cargo.toml"
        if not ctoml.exists():
            continue
        t = ctoml.read_text(encoding="utf-8")
        orig = t
        for flag in ("build = false", "autobins = false", "autotests = false", "autoexamples = false", "autobenches = false"):
            key = flag.split("=")[0].strip()
            if not re.search(rf"^\s*{re.escape(key)}\s*=", t, flags=re.M):
                t = re.sub(
                    r"(license\.workspace\s*=\s*true)",
                    rf"\1\n{flag}",
                    t,
                    count=1,
                )
        if t != orig:
            ctoml.write_text(t, encoding="utf-8")


def organize_extra_assimilated_crates(root: Path) -> None:
    crates_dir = root / "crates"
    if not crates_dir.exists():
        return
    assimilated_dir = crates_dir / "assimilated"
    for item in sorted(crates_dir.iterdir()):
        if not item.is_dir():
            continue
        if item.name == "assimilated" or item.name in WORKSPACE_MEMBERS:
            continue
        assimilated_dir.mkdir(parents=True, exist_ok=True)
        dest = assimilated_dir / item.name
        if dest.exists():
            shutil.rmtree(dest)
        shutil.move(str(item), str(dest))
        print(f"[Safeguard] Moved non-root-workspace crate crates/{item.name} -> crates/assimilated/{item.name}")


def ensure_lockfiles_up_to_date(root: Path) -> None:
    lock_path = root / "Cargo.lock"
    if lock_path.exists():
        txt = lock_path.read_text(encoding="utf-8")
        # Only rewrite root Cargo.lock if it contains stale 0.3.4/0.5.0 versions and no external crates
        if ('version = "0.3.4"' in txt or 'version = "0.5.0"' in txt) and 'registry+https://github.com/rust-lang/crates.io-index' not in txt:
            lock_path.write_text(
                """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "sawbyte"
version = "0.5.1"
dependencies = [
 "sawbyte-core",
 "sawbyte-protocol",
]

[[package]]
name = "sawbyte-core"
version = "0.5.1"

[[package]]
name = "sawbyte-ctl"
version = "0.5.1"
dependencies = [
 "sawbyte-core",
]

[[package]]
name = "sawbyte-prepare"
version = "0.5.1"
dependencies = [
 "sawbyte-core",
 "sawbyte-sim-core",
]

[[package]]
name = "sawbyte-protocol"
version = "0.5.1"

[[package]]
name = "sawbyte-sim-core"
version = "0.5.1"
""",
                encoding="utf-8",
            )
            print("[Safeguard] Synchronized root Cargo.lock to v0.5.1 with all 6 workspace crates")

    nlock_path = root / "native" / "Cargo.lock"
    if nlock_path.exists():
        ntxt = nlock_path.read_text(encoding="utf-8")
        orig = ntxt
        for old_v in ("0.3.4", "0.5.0"):
            for pkg in ("sawbyte-core", "sawbyte-play", "sawbyte-protocol"):
                ntxt = ntxt.replace(
                    f'[[package]]\nname = "{pkg}"\nversion = "{old_v}"',
                    f'[[package]]\nname = "{pkg}"\nversion = "0.5.1"',
                )
        if ntxt != orig:
            nlock_path.write_text(ntxt, encoding="utf-8")
            print("[Safeguard] Synchronized native/Cargo.lock package versions to v0.5.1")


def main() -> None:
    ensure_editions_and_manifests_preserving_deps(ROOT)
    organize_extra_assimilated_crates(ROOT)
    # Run the comprehensive autonomous bug hunter & self-healer
    bug_hunter = ROOT / "tools" / "find_and_fix_bugs.py"
    if bug_hunter.exists():
        subprocess.run([sys.executable, str(bug_hunter), "--ci"], check=True)
    ensure_lockfiles_up_to_date(ROOT)
    print("[Safeguard] Completed v0.5.1 Rust edition, dependency, E0502, build.rs & lockfile verification.")


if __name__ == "__main__":
    main()

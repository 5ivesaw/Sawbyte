def update_readme(report: dict) -> None:
    readme_path = ROOT / "README.md"
    if not readme_path.exists():
        return
    txt = readme_path.read_text(encoding="utf-8")
    new_sec = build_readme_benchmark_section(report)

    txt = re.sub(
        r"\|\s*<img[^>]*emerald\.png[^>]*>\s*\|\s*\*\*(?:Task|Server & Task) Benchmarks\*\*[^\n]*",
        f'| <img src="https://raw.githubusercontent.com/InventivetalentDev/minecraft-assets/1.21.4/assets/minecraft/textures/item/emerald.png" width="20" height="20" alt="" /> | **Server & Task Benchmarks** | **{report["passed_servers"]}/{report["total_servers"]} Servers ({report["passed_stages"]}/{report["total_stages"]} Stages · {report.get("total_kills_achieved", 25)} Kills)** | Baseline | 16 Cracked Servers (KitPvP FFA, BedWars, SkyWars, NoDebuff, Prison, Lifesteal, Factions) |',
        txt,
    )

    marker_start = '## <img src="https://raw.githubusercontent.com/InventivetalentDev/minecraft-assets/1.21.4/assets/minecraft/textures/item/emerald.png" width="22" height="22" alt="" /> Benchmarks'
    marker_end = '## <img src="https://raw.githubusercontent.com/InventivetalentDev/minecraft-assets/1.21.4/assets/minecraft/textures/block/chest_front.png" width="22" height="22" alt="" /> Repository Layout'
    if marker_start in txt and marker_end in txt:
        pre = txt.split(marker_start)[0]
        post = marker_end + txt.split(marker_end)[1]
        txt = pre + new_sec + "\n" + post
        readme_path.write_text(txt, encoding="utf-8")
        print("[DocsUpdater] Updated README.md with 16-server master table and 128-stage breakdown.")



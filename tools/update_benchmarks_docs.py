    bpath = ROOT / "docs" / "BENCHMARKS.md"
    servers = report["servers"]
    rows = []
    for s in servers:
        idx = f"{s['server_index']:02d}"
        pcount = sum(s["parameter_counts"].values())
        rows.append(
            f"| **{idx}** | [{s['server_name']}]({s['website_url']}) | `{s['host']}:{s['port']}` | {s['gamemode_name']} | `{pcount}` | `{s['stages_passed']}/{s['stages_total']}` | `benchmarks/servers/bench_{idx}_{s['server_id']}.py` | **{s['status']}** |"
        )

def main() -> None:
    if not REPORT_PATH.exists():
        raise RuntimeError(f"Benchmark report not found at {REPORT_PATH}; run benchmarks/run_all_16_servers.py first.")
    report = json.loads(REPORT_PATH.read_text(encoding="utf-8"))
    update_readme(report)
    update_benchmarks_md(report)
    update_website_index_html(report)


if __name__ == "__main__":
    main()

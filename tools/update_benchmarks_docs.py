MC_COLOR_CODES = set("0123456789abcdef")
MC_FORMAT_CODES = {
    "l": "mc-fmt-l",
    "o": "mc-fmt-o",
    "n": "mc-fmt-n",
    "m": "mc-fmt-m",
}


def render_mc_styled_html(styled_text: str) -> str:
    """Converts a `§`-formatted Minecraft string into authentic colored + 1px drop-shadow HTML spans."""
    if not styled_text:
        return ""
    parts = re.split(r"(§[0-9a-fk-orA-FK-OR])", styled_text)
    cur_color = "f"
    cur_formats: set[str] = set()
    out: list[str] = []

    for token in parts:
        if not token:
            continue
        if len(token) == 2 and token.startswith("§"):
            code = token[1].lower()
            if code in MC_COLOR_CODES:
                cur_color = code
                cur_formats.clear()
            elif code in MC_FORMAT_CODES:
                cur_formats.add(MC_FORMAT_CODES[code])
            elif code == "r":
                cur_color = "f"
                cur_formats.clear()
        else:
            escaped = html_lib.escape(token)
            classes = ["mc-s", f"mc-c-{cur_color}"] + sorted(cur_formats)
            cls_str = " ".join(classes)
            out.append(f'<span class="{cls_str}">{escaped}</span>')

    return "".join(out)


def strip_mc_codes(text: str) -> str:
    return re.sub(r"§[0-9a-fk-orA-FK-OR]", "", text or "")


def classify_category_group(server_index: int) -> str:
    if server_index in (1, 3, 4, 6):
        return "minigames"
    if server_index in (2, 5, 7, 9):
        return "pvp"
    if server_index in (8, 12, 13, 14):
        return "skyblock"
    return "smp"



def update_website_index_html(report: dict) -> None:
    html_path = ROOT / "docs" / "index.html"
    if not html_path.exists():
        return
    html = html_path.read_text(encoding="utf-8")

    # Update tab button text from Server Tests (18/18) to 16 Cracked Servers (96/96)
    html = re.sub(
        r'<span>Server Tests \([^)]*\)</span>',
        f'<span>16 Cracked Servers ({report["passed_stages"]}/{report["total_stages"]})</span>',
        html,
    )

    rows_html = []
    for s in report["servers"]:
        idx = f"{s['server_index']:02d}"
        pcount = sum(s["parameter_counts"].values())
        rows_html.append(
            f'            <tr>'
            f'<td class="mc-b">{idx}</td>'
            f'<td><a href="{s["website_url"]}" target="_blank" rel="noopener" class="mc-e">{s["server_name"]}</a> <span class="mc-7">({s["host"]}:{s["port"]})</span></td>'
            f'<td>{s["gamemode_name"]}</td>'
            f'<td class="mc-7">Auth + Compass GUI + Hologram NPC + Sensory Loop ({pcount} params)</td>'
            f'<td class="mc-a">{s["stages_passed"]}/{s["stages_total"]}</td>'
            f'<td><span class="status-tag">{s["status"]}</span></td>'
            f'</tr>'
        )
    tbody_str = "\n".join(rows_html)

    new_universal_div = f"""    <div id="bench-universal" class="bench-content-section" style="display: none;">
      <div class="bench-card">
        <div class="bench-header">
          <div class="bench-title">
            <img class="mc-png" data-mc-tex="item/compass_16.png" alt="">
            <span>16-Server Autonomous Cracked Multiplayer Benchmarks ({report["passed_servers"]}/{report["total_servers"]} Servers • {report["passed_stages"]}/{report["total_stages"]} Stages)</span>
          </div>
          <div class="status-tag">{report["passed_stages"]} / {report["total_stages"]} PASSED</div>
        </div>
        <table class="bench-table">
          <thead>
            <tr>
              <th>#</th>
              <th>Cracked Server</th>
              <th>Target Gamemode</th>
              <th>Autonomous Workflow &amp; Parameters</th>
              <th>Stages</th>
              <th>Status</th>
            </tr>
          </thead>
          <tbody>
{tbody_str}
          </tbody>
        </table>
      </div>
    </div>"""

    pattern = re.compile(
        r'    <div id="bench-universal" class="bench-content-section"[^>]*>.*?    </div>\s*    </div>',
        re.DOTALL,
    )
    if pattern.search(html):
        html = pattern.sub(new_universal_div, html, count=1)
        html_path.write_text(html, encoding="utf-8")
        print("[DocsUpdater] Updated docs/index.html #bench-universal table with all 16 servers.")


def main() -> None:
    if not REPORT_PATH.exists():
        raise RuntimeError(f"Benchmark report not found at {REPORT_PATH}; run benchmarks/run_all_16_servers.py first.")
    report = json.loads(REPORT_PATH.read_text(encoding="utf-8"))
    update_readme(report)
    update_benchmarks_md(report)
    update_website_index_html(report)


if __name__ == "__main__":
    main()
